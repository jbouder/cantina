#!/usr/bin/env node
// Writes the files the site builds from the rest of the repository, so
// they cannot drift from it:
//
// - src/generated/theme.css: the skin palettes the site is drawn in,
//   copied from packages/skins/tokens/. Classic is the dark theme and
//   Brushed metal the light one; only the selectors change.
// - public/og.png: the social preview image, drawn in Classic's tokens.
// - public/schemas/: the JSON schemas, copied from schemas/ at the root,
//   which the Rust tests generate from the types.
//
//   node scripts/generate.mjs
import { cpSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import sharp from "sharp";

const docs = new URL("..", import.meta.url).pathname;
const tokens = join(docs, "..", "packages", "skins", "tokens");
const generated = join(docs, "src", "generated");
mkdirSync(generated, { recursive: true });

cpSync(join(docs, "..", "schemas"), join(docs, "public", "schemas"), { recursive: true });

/** A skin's token file with its selector swapped for one of the site's themes. */
function theme(id, selector) {
  const css = readFileSync(join(tokens, `${id}.css`), "utf8");
  const block = /^[^{]*\{/m;
  if (!block.test(css)) throw new Error(`no token block in ${id}.css`);
  return css.replace(block, `${selector} {`);
}

writeFileSync(
  join(generated, "theme.css"),
  [
    "/* Generated by scripts/generate.mjs from packages/skins/tokens/. Do not edit. */",
    theme("classic", ":root"),
    theme("metal", ':root[data-theme="light"]'),
  ].join("\n"),
);

/** The hex value of a token in a skin's file. */
function token(id, name) {
  const css = readFileSync(join(tokens, `${id}.css`), "utf8");
  const m = css.match(new RegExp(`--${name}:\\s*(#[0-9a-f]{3,8})\\s*;`, "i"));
  if (!m) throw new Error(`--${name} is not a hex value in ${id}.css`);
  return m[1];
}

const c = Object.fromEntries(
  [
    "frame-hi",
    "frame",
    "frame-lo",
    "frame-edge",
    "title-on",
    "title-text",
    "lcd-fg",
    "ink-dim",
  ].map((name) => [name, token("classic", name)]),
);
const rules = (x, y) =>
  [0, 8, 16]
    .map((d) => `<rect x="${x}" y="${y + d}" width="250" height="3" fill="${c["title-on"]}"/>`)
    .join("");
const og = `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630">
  <defs><linearGradient id="f" x1="0" y1="0" x2="0" y2="1">
    <stop offset="0" stop-color="${c.frame}"/><stop offset="1" stop-color="${c["frame-lo"]}"/>
  </linearGradient></defs>
  <rect width="1200" height="630" fill="${c["frame-edge"]}"/>
  <rect x="24" y="24" width="1152" height="582" rx="14" fill="url(#f)" stroke="${c["frame-hi"]}" stroke-width="2"/>
  ${rules(150, 92)}${rules(800, 92)}
  <text x="600" y="120" text-anchor="middle" font-family="Verdana, sans-serif" font-weight="700"
    font-size="44" letter-spacing="14" fill="${c["title-text"]}">CANTINA</text>
  <rect x="110" y="190" width="980" height="220" rx="6" fill="${c["frame-edge"]}" stroke="${c["frame-hi"]}"/>
  <text x="600" y="295" text-anchor="middle" font-family="Menlo, monospace" font-size="56"
    fill="${c["lcd-fg"]}">PLUG IN. PLAY THROUGH.</text>
  <text x="600" y="365" text-anchor="middle" font-family="Menlo, monospace" font-size="30"
    fill="${c["lcd-fg"]}">pedals · tracks · drums · plugins · stage</text>
  <text x="600" y="510" text-anchor="middle" font-family="Verdana, sans-serif" font-size="30"
    fill="${c["ink-dim"]}">A Mac studio for guitar and bass players. Open source.</text>
</svg>`;
mkdirSync(join(docs, "public"), { recursive: true });
await sharp(Buffer.from(og))
  .png()
  .toFile(join(docs, "public", "og.png"));
