#!/usr/bin/env node
// Writes the generated references of the cantina-author skill from the
// files Cantina itself is built from, so the skill cannot drift from them:
//
// - references/node-catalog.md: every pedal node kind and its fields,
//   from ui/src/lib/pedal-kinds.json (the catalog `cantina-cli kinds
//   --json` prints and the designer reads).
// - references/formats.md: every field of every format, from the JSON
//   Schemas in schemas/ that the Rust tests generate from the types.
//
//   node scripts/skill-references.mjs           # rewrite them
//   node scripts/skill-references.mjs --check   # fail if they are stale (CI)
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const out = join(root, ".claude", "skills", "cantina-author", "references");
const HEADER =
  "<!-- Generated by scripts/skill-references.mjs. Do not edit; run `node scripts/skill-references.mjs`. -->\n\n";

/** A number as the catalog means it, without float noise. */
function num(n) {
  return Number.isInteger(n) ? String(n) : String(Number(n.toPrecision(6)));
}

function catalog() {
  const kinds = JSON.parse(readFileSync(join(root, "ui/src/lib/pedal-kinds.json"), "utf8"));
  const lines = [
    "# Pedal node catalog",
    "",
    "Every `kind` a pedal node can be, with its fields. A field takes a constant",
    "or a binding (`{\"param\": ...}` or, where marked modulatable, `{\"node\": ...}`).",
    "Smoothed fields ease toward a parameter change over the node's `smooth` time.",
    "`cantina-cli kinds` prints the same catalog.",
    "",
  ];
  for (const k of kinds) {
    const traits = [
      k.source ? "source: takes no audio in" : null,
      k.control ? "control: bind it, never wire it" : null,
      k.sums ? "sums any number of incoming edges" : null,
    ].filter(Boolean);
    lines.push(`## \`${k.kind}\`: ${k.label}`, "", k.summary);
    if (traits.length) lines.push("", `*${traits.join("; ")}.*`);
    lines.push("");
    if (k.fields.length === 0) {
      lines.push("No fields.", "");
      continue;
    }
    lines.push("| Field | Takes | Default | | What it does |", "| --- | --- | --- | --- | --- |");
    for (const f of k.fields) {
      const t = f.kind;
      let takes;
      let def;
      if (t.type === "number") {
        takes = `${num(t.min)} to ${num(t.max)}${t.unit ? ` ${t.unit}` : ""}`;
        def = num(t.default);
      } else if (t.type === "name") {
        takes = t.options.map((o) => `\`${o}\``).join(", ");
        def = `\`${t.options[t.default]}\``;
      } else {
        takes = "true or false";
        def = String(t.default);
      }
      const how = [f.modulatable ? "modulatable" : null, f.smoothed ? "smoothed" : null]
        .filter(Boolean)
        .join(", ");
      lines.push(`| \`${f.name}\` | ${takes} | ${def} | ${how} | ${f.summary} |`);
    }
    lines.push("");
  }
  return lines.join("\n");
}

/** A short description of what a schema node accepts. */
function describe(s, defs) {
  if (!s) return "";
  if (s.$ref) return `\`${s.$ref.split("/").pop()}\``;
  if (s.const !== undefined) return `exactly \`${JSON.stringify(s.const)}\``;
  if (s.enum) return s.enum.map((e) => `\`${JSON.stringify(e)}\``).join(", ");
  if (s.anyOf || s.oneOf) {
    return (s.anyOf ?? s.oneOf)
      .map((x) => describe(x, defs))
      .filter((x) => x && x !== "null")
      .join(" or ");
  }
  const types = [s.type ?? []].flat().filter((t) => t !== "null");
  let text = types.join(" or ");
  if (types.includes("array")) {
    const items = Array.isArray(s.prefixItems)
      ? `[${s.prefixItems.map((x) => describe(x, defs)).join(", ")}]`
      : describe(s.items, defs);
    text = `array of ${items}`;
  }
  const limits = [];
  if (s.minimum !== undefined) limits.push(`≥ ${s.minimum}`);
  if (s.exclusiveMinimum !== undefined) limits.push(`> ${s.exclusiveMinimum}`);
  if (s.maximum !== undefined && !(s.format?.startsWith("uint") && s.maximum > 1e4))
    limits.push(`≤ ${s.maximum}`);
  if (!s.prefixItems && s.minItems !== undefined) limits.push(`at least ${s.minItems}`);
  if (!s.prefixItems && s.maxItems !== undefined) limits.push(`at most ${s.maxItems}`);
  if (s.minLength !== undefined) limits.push("not empty");
  if (s.pattern) limits.push(`matching \`${s.pattern}\``);
  return limits.length ? `${text} (${limits.join(", ")})` : text;
}

function table(title, s, defs) {
  const props = s.properties ?? {};
  const required = new Set(s.required ?? []);
  const lines = [title, ""];
  if (s.description) lines.push(s.description, "");
  lines.push("| Field | Required | Takes | What it is |", "| --- | --- | --- | --- |");
  for (const [name, p] of Object.entries(props)) {
    if (name === "$schema") continue;
    const desc = (p.description ?? "").replace(/\|/g, "\\|");
    const dflt = p.default !== undefined ? ` Default \`${JSON.stringify(p.default)}\`.` : "";
    lines.push(
      `| \`${name}\` | ${required.has(name) ? "yes" : ""} | ${describe(p, defs).replace(/\|/g, "\\|")} | ${desc}${dflt} |`,
    );
  }
  lines.push("");
  return lines;
}

function formats() {
  const order = [
    ["pedal", "`*.pedal.json` in `~/Music/Cantina/Pedals/`"],
    ["kit", "`kit.json` in a folder of `~/Music/Cantina/Kits/`"],
    ["kit-recipe", "`*.recipe.json`, turned into a kit by `cantina-cli synth-kit`"],
    ["pattern", "`*.pattern.json` in `~/Music/Cantina/Patterns/`"],
    ["tab", "`*.tab.json`; inside a project, as a clip's `tab`"],
    ["rig", "`*.rig.json`, checked and rendered by `cantina-cli`"],
    ["jam", "`*.jam.json`, checked by `cantina-cli`"],
    ["exercise", "`*.exercise.json`, checked and rendered by `cantina-cli`"],
    ["course", "`*.course.json` in `~/Music/Cantina/Courses/`, checked by `cantina-cli`"],
    ["practice-log", "`~/Music/Cantina/Practice/log.json`, written by Cantina; read it, do not write it"],
    ["project", "`project.json` in a `Name.cantina/` folder"],
  ];
  const lines = [
    "# Formats",
    "",
    "Every field of every format Cantina reads, from the JSON Schemas in",
    "`schemas/` (also `cantina-cli schema <format>`). A file may carry a",
    '`"$schema"` field naming its schema; Cantina ignores it.',
    "",
  ];
  for (const [name, where] of order) {
    const s = JSON.parse(readFileSync(join(root, "schemas", `${name}.schema.json`), "utf8"));
    lines.push(...table(`## ${s.title} (\`${name}\`)`, s, s.$defs ?? {}));
    lines.push(`Where it goes: ${where}. Schema: \`${s.$id}\`.`, "");
    if (name === "pedal") {
      lines.push(
        "Node fields depend on the node's `kind`; see [node-catalog.md](node-catalog.md).",
        "",
      );
    }
    for (const [defName, def] of Object.entries(s.$defs ?? {})) {
      if (!def.properties || name === "pedal" && defName === "NodeDef") continue;
      lines.push(...table(`### \`${defName}\``, def, s.$defs));
    }
  }
  return lines.join("\n");
}

const files = { "node-catalog.md": catalog(), "formats.md": formats() };
const check = process.argv.includes("--check");
let stale = false;
for (const [file, body] of Object.entries(files)) {
  const path = join(out, file);
  const text = HEADER + body.trimEnd() + "\n";
  if (check) {
    let now = "";
    try {
      now = readFileSync(path, "utf8");
    } catch {}
    if (now !== text) {
      console.error(`${path} is stale; run node scripts/skill-references.mjs`);
      stale = true;
    }
  } else {
    writeFileSync(path, text);
    console.log(`wrote ${path}`);
  }
}
if (stale) process.exit(1);
