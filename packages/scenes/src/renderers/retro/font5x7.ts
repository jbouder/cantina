const GLYPHS = new Map<string, Uint8Array>(
  Object.entries(RAW).map(([ch, bits]) => [ch, Uint8Array.from(bits, (c) => (c === '#' ? 1 : 0))]),
);
const BLANK = GLYPHS.get(' ')!;

export const GLYPH_W = 5;
export const GLYPH_H = 7;

export function hasGlyph(ch: string): boolean {
  return GLYPHS.has(ch.toUpperCase());
}

/** 35 entries, row-major; 1 = lit. Unknown characters are blank. */
export function glyph(ch: string): Uint8Array {
  return GLYPHS.get(ch.toUpperCase()) ?? BLANK;
}

/** Draws text into packed pixels at (x, y), each font pixel scale x scale. */
export function drawText(px: Uint32Array, width: number, height: number, x: number, y: number, text: string, color: number, scale = 1): void {
  for (let i = 0; i < text.length; i++) {
    const bits = glyph(text[i]);
    const ox = x + i * (GLYPH_W + 1) * scale;
    for (let gy = 0; gy < GLYPH_H; gy++) {
      for (let gx = 0; gx < GLYPH_W; gx++) {
        if (!bits[gy * GLYPH_W + gx]) continue;
        for (let sy = 0; sy < scale; sy++) {
          const yy = y + gy * scale + sy;
          if (yy < 0 || yy >= height) continue;
          for (let sx = 0; sx < scale; sx++) {
            const xx = ox + gx * scale + sx;
            if (xx >= 0 && xx < width) px[yy * width + xx] = color;
          }
        }
      }
    }
  }
}

export function textWidth(text: string, scale = 1): number {
  return text.length * (GLYPH_W + 1) * scale - scale;
}
